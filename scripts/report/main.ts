// `npm run report`: a markdown summary of every solved flop — the raiser's
// first decision (check / bet sizes), the caller's answer to each c-bet
// (fold / call / raise), per flop and per board family (weighted by how many
// real flops each stands for). For checking the solver against published
// GTO numbers. Writes docs/solver-report.md and prints it.

import { mkdirSync, readFileSync, readdirSync, existsSync, writeFileSync } from 'node:fs';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseCards } from '@/poker/cards';
import { FAMILIES, FAMILY_NAME, classifyFlop, flopWeight } from '@/poker/texture';
import { decodeFlop } from '@/postflop/decode';
import { POSTFLOP_SPOTS, nodeKind } from '@/postflop/spots';
import type { SolvedFlop, StoredFlop } from '@/postflop/types';
import { nodeAt, nodeTotals } from '@/postflop/view';

const here = dirname(fileURLToPath(import.meta.url));
const root = process.env.POKER_ROOT ?? resolve(here, '..', '..');
const dataDir = join(root, 'src', 'data', 'postflop');

const pct = (x: number) => `${Math.round(x * 100)}`;

interface Row {
  flop: string;
  family: string;
  weight: number;
  exploit: number;
  cbet: { check: number; sizes: Record<string, number> };
  vs: Record<string, { fold: number; call: number; raise: number }>;
}

function rowOf(spot: (typeof POSTFLOP_SPOTS)[number], f: SolvedFlop): Row {
  const cards = parseCards(f.board);
  const first = f.nodes.find((n) => nodeKind(n.path, n.player, spot.pfr) === 'cbet')!;
  const t = nodeTotals(f, first);
  const sizes: Record<string, number> = {};
  let check = 0;
  first.actions.forEach((a, k) => {
    if (a.kind === 'check') check = t[k]!;
    else sizes[a.id] = (sizes[a.id] ?? 0) + t[k]!;
  });
  const vs: Row['vs'] = {};
  for (const a of first.actions) {
    if (a.kind === 'check') continue;
    const nd = nodeAt(f, first.path ? `${first.path}-${a.id}` : a.id);
    if (!nd) continue;
    const tt = nodeTotals(f, nd);
    const r = { fold: 0, call: 0, raise: 0 };
    nd.actions.forEach((x, k) => {
      if (x.kind === 'fold') r.fold += tt[k]!;
      else if (x.kind === 'call') r.call += tt[k]!;
      else r.raise += tt[k]!;
    });
    vs[a.id] = r;
  }
  return { flop: f.board, family: classifyFlop(cards).family, weight: flopWeight(cards), exploit: f.exploit, cbet: { check, sizes }, vs };
}

const out: string[] = ['# Solver report', '', 'Generated by `npm run report` from `src/data/postflop/`. Frequencies in % of the acting range.', ''];
for (const spot of POSTFLOP_SPOTS) {
  const dir = join(dataDir, spot.id);
  if (!existsSync(dir)) continue;
  const files = readdirSync(dir).filter((x) => x.endsWith('.json'));
  if (!files.length) continue;
  const rows = files.map((file) => rowOf(spot, decodeFlop(JSON.parse(readFileSync(join(dir, file), 'utf8')) as StoredFlop)));
  const sizeIds = [...new Set(rows.flatMap((r) => Object.keys(r.cbet.sizes)))];
  const raiser = spot.pfr === 1 ? spot.ip : spot.oop;
  const caller = spot.pfr === 1 ? spot.oop : spot.ip;
  out.push(`## ${spot.name} (${spot.pot === 'srp' ? 'single-raised' : '3-bet pot'}, pot ${spot.tree.pot} bb)`, '');
  out.push(`${raiser} c-bets (check / ${sizeIds.join(' / ')}); ${caller} facing each size (fold / call / raise).`, '');
  out.push(`| Family | Flops | Bet % | ${sizeIds.map((s) => `${s} %`).join(' | ')} | ${sizeIds.map((s) => `vs ${s} f/c/r`).join(' | ')} |`);
  out.push(`|---|---|---|${sizeIds.map(() => '---').join('|')}|${sizeIds.map(() => '---').join('|')}|`);
  const famRow = (label: string, rs: Row[]) => {
    const w = rs.reduce((s, r) => s + r.weight, 0);
    const avg = (f: (r: Row) => number) => rs.reduce((s, r) => s + f(r) * r.weight, 0) / w;
    const bet = 1 - avg((r) => r.cbet.check);
    const sizes = sizeIds.map((id) => pct(avg((r) => r.cbet.sizes[id] ?? 0)));
    const vs = sizeIds.map((id) => `${pct(avg((r) => r.vs[id]?.fold ?? 0))}/${pct(avg((r) => r.vs[id]?.call ?? 0))}/${pct(avg((r) => r.vs[id]?.raise ?? 0))}`);
    out.push(`| ${label} | ${rs.length} | **${pct(bet)}** | ${sizes.join(' | ')} | ${vs.join(' | ')} |`);
  };
  for (const fam of FAMILIES) {
    const rs = rows.filter((r) => r.family === fam);
    if (rs.length) famRow(FAMILY_NAME[fam], rs);
  }
  famRow('**All solved flops**', rows);
  out.push('', '<details><summary>Per flop</summary>', '', `| Flop | Family | Bet % | ${sizeIds.map((s) => `${s} %`).join(' | ')} | ${sizeIds.map((s) => `vs ${s} f/c/r`).join(' | ')} | Exploit % pot |`);
  out.push(`|---|---|---|${sizeIds.map(() => '---').join('|')}|${sizeIds.map(() => '---').join('|')}|---|`);
  for (const r of rows.sort((a, b) => FAMILIES.indexOf(a.family as never) - FAMILIES.indexOf(b.family as never))) {
    out.push(
      `| ${r.flop} | ${FAMILY_NAME[r.family as keyof typeof FAMILY_NAME]} | ${pct(1 - r.cbet.check)} | ${sizeIds.map((id) => pct(r.cbet.sizes[id] ?? 0)).join(' | ')} | ${sizeIds
        .map((id) => (r.vs[id] ? `${pct(r.vs[id]!.fold)}/${pct(r.vs[id]!.call)}/${pct(r.vs[id]!.raise)}` : '–'))
        .join(' | ')} | ${(r.exploit * 100).toFixed(2)} |`,
    );
  }
  out.push('', '</details>', '');
}
const text = out.join('\n');
mkdirSync(join(root, 'docs'), { recursive: true });
writeFileSync(join(root, 'docs', 'solver-report.md'), text);
console.log(text);
